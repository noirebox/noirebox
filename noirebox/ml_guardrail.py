from __future__ import annotations

import hashlib
import os
import stat
from dataclasses import dataclass
from pathlib import Path

import joblib

_ROOT = Path(__file__).resolve().parent.parent
_PKG = Path(__file__).resolve().parent


def _model_path(name: str) -> Path:
    """Locates a model: pip package first, cloned repo second.

    `pip install noirebox` ships the .joblib files inside the package; a git
    clone leaves them in models/ (generated by make train). The fallback
    returns the repo path so the _load error message stays consistent with
    `make train`.
    """
    for base in (_PKG, _ROOT):
        candidate = base / "models" / name
        if candidate.exists():
            return candidate
    return _ROOT / "models" / name


_MODEL_PATHS = {
    "fr": _model_path("detector.joblib"),
    "en": _model_path("detector_en.joblib"),
    "es": _model_path("detector_es.joblib"),
}
_pipelines: dict[str, object] = {}


@dataclass
class MLDetection:
    """Same contract as guardrail.Incident — a drop-in replacement."""

    category: str
    score: float
    excerpt: str

    def as_dict(self) -> dict:
        return {"category": self.category, "score": round(self.score, 3),
                "excerpt": self.excerpt}


def model_available(lang: str = "fr") -> bool:
    path = _MODEL_PATHS.get(lang)
    return path is not None and path.exists()


def _verify_model_file(path: Path, lang: str) -> None:
    """The integrity gate before joblib.load (NB-08): a model file is
    PICKLE — loading it executes code, so the load refuses a file another
    local account could have rewritten (world-writable), and honors an
    optional operator pin, NOIREBOX_MODEL_SHA256_<LANG> (upper-cased lang).
    The pin is opt-in on purpose: `make train` regenerates the models per
    machine, so a hard-coded hash would break the documented workflow —
    deployments that train elsewhere and copy the artifacts pin them."""
    st = path.stat()
    if os.name != "nt" and st.st_mode & stat.S_IWOTH:
        raise RuntimeError(
            f"refusing to load a world-writable model file: {path} "
            f"(chmod o-w required — joblib.load executes code)")
    expected = os.environ.get(f"NOIREBOX_MODEL_SHA256_{lang.upper()}")
    if expected:
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != expected.strip().lower():
            raise RuntimeError(
                f"model integrity check failed for {path.name}: "
                f"expected {expected.strip().lower()}, got {actual}")


def _load(lang: str):
    if lang in _pipelines:
        return _pipelines[lang]
    path = _MODEL_PATHS.get(lang)
    if path is None:
        raise ValueError(f"unknown language: {lang!r} (supported: {sorted(_MODEL_PATHS)})")
    if not path.exists():
        raise FileNotFoundError(
            f"models/detector{'' if lang == 'fr' else '_en'}.joblib missing — "
            f"run `make train{'-en' if lang == 'en' else ''}`"
        )
    _verify_model_file(path, lang)
    _pipelines[lang] = joblib.load(path)
    return _pipelines[lang]


def predict_line(line: str, lang: str = "fr") -> MLDetection:
    """Classifies ONE line of text (a single transcript sentence)."""
    pipeline = _load(lang)
    category = pipeline.predict([line])[0]
    score = float(pipeline.predict_proba([line])[0].max())
    return MLDetection(category, score, line.strip()[:120])


def scan_ml(text: str, min_confidence: float = 0.5, lang: str = "fr") -> list[dict]:
    """Scans a text line by line → incidents in NoireBox format.

    Line by line because the model was trained on sentences — one utterance,
    one detection. `min_confidence` drops detections below the threshold;
    the false-positive/false-negative trade-off it sets is a documented
    product choice, not a hidden one.

    The `start`/`end` offsets (position of the line within the full text)
    match the regex incidents' output format, so the pipeline filters
    compromised lines regardless of the engine.
    """
    detections = []
    offset = 0
    for raw in text.splitlines():
        start, end = offset, offset + len(raw)
        offset = end + 1
        line = raw.strip()
        if not line:
            continue
        detection = predict_line(line, lang=lang)
        if detection.category != "clean" and detection.score >= min_confidence:
            entry = detection.as_dict()
            entry["start"], entry["end"] = start, end
            detections.append(entry)
    return detections
